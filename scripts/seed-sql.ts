/* Writes supabase/seed.sql from seed.json, for pasting into the Supabase SQL editor
   (an alternative to `npm run seed`). Existing rows are kept. Usage: npx tsx scripts/seed-sql.ts */
import { readFileSync, writeFileSync } from 'node:fs';
import { seedDocs } from '../lib/seed';

const { agents, projects } = seedDocs(JSON.parse(readFileSync('seed.json', 'utf8')));
const quote = (s: string) => {
  if (s.includes('$seed$')) throw new Error('seed data contains the quote tag');
  return '$seed$' + s + '$seed$';
};
const rows = (table: string, docs: Record<string, unknown>) =>
  Object.entries(docs).map(([id, d]) => `insert into public.${table} (id, data) values (${quote(id)}, ${quote(JSON.stringify(d))}::jsonb) on conflict (id) do nothing;`).join('\n');
writeFileSync('supabase/seed.sql', '-- Generated by scripts/seed-sql.ts from seed.json. Run after schema.sql. Safe to re-run.\n'
  + rows('agents', agents) + '\n' + rows('projects', projects) + '\n');
console.log(`supabase/seed.sql: ${Object.keys(agents).length} agents, ${Object.keys(projects).length} projects`);
